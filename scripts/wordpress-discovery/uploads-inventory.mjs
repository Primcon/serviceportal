#!/usr/bin/env node
/**
 * WordPress uploads inventory (migration step M1).
 *
 * Read-only. Walks a copy of wp-content/uploads and reports how many files there are and
 * how much space they take, by file type and by year folder. It prints no file names.
 *
 *   node scripts/wordpress-discovery/uploads-inventory.mjs <path-to-uploads-folder>
 */
import { readdir, stat } from "node:fs/promises";
import { extname, join, relative, sep } from "node:path";

const root = process.argv[2];
if (!root) {
  console.error("Usage: node uploads-inventory.mjs <path-to-wp-content/uploads>");
  process.exit(1);
}

// WordPress generates resized copies named like photo-300x200.jpg next to each original.
const resizedCopy = /-\d+x\d+\.[a-z0-9]+$/i;
const totals = { files: 0, bytes: 0, resizedCopies: 0, resizedBytes: 0 };
const byType = new Map();
const byYear = new Map();

function add(map, key, bytes) {
  const entry = map.get(key) ?? { files: 0, bytes: 0 };
  entry.files += 1;
  entry.bytes += bytes;
  map.set(key, entry);
}

async function walk(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const fullPath = join(directory, entry.name);
    if (entry.isDirectory()) {
      await walk(fullPath);
      continue;
    }
    if (!entry.isFile()) continue;
    const { size } = await stat(fullPath);
    totals.files += 1;
    totals.bytes += size;
    if (resizedCopy.test(entry.name)) {
      totals.resizedCopies += 1;
      totals.resizedBytes += size;
      continue;
    }
    add(byType, extname(entry.name).toLowerCase() || "(none)", size);
    const firstFolder = relative(root, fullPath).split(sep)[0];
    add(byYear, /^\d{4}$/.test(firstFolder) ? firstFolder : "(not in a year folder)", size);
  }
}

const megabytes = (bytes) => (bytes / 1024 / 1024).toFixed(1);

await walk(root);
console.log(`Total: ${totals.files} files, ${megabytes(totals.bytes)} MB`);
console.log(`Resized copies generated by WordPress (not migrated): ${totals.resizedCopies} files, ${megabytes(totals.resizedBytes)} MB`);
console.log("\nOriginals by file type:");
console.table([...byType].sort((a, b) => b[1].bytes - a[1].bytes).map(([type, value]) => ({ type, files: value.files, mb: megabytes(value.bytes) })));
console.log("Originals by year folder:");
console.table([...byYear].sort(([a], [b]) => a.localeCompare(b)).map(([year, value]) => ({ year, files: value.files, mb: megabytes(value.bytes) })));
